def f(x, n=2):
    if x is None:
        return "nan"
    try:
        return f"{x:.{n}f}"
    except Exception:
        return str(x)


def rci(b, n=2):
    a = b["arh_r"]
    return f"{f(a['r'], n)} [{f(a['ci'][0], n)}, {f(a['ci'][1], n)}] (p={f(a['p_one'], 3)})"


def trs(b, n=2):
    t = b["tr_lm"]
    return f"{f(t['Tr'], n)} (p={f(t['p_one'], 3)})"


def trv(b, n=2):
    t = b["tr_vis"]
    return f"{f(t['Tr'], n)} (p={f(t['p_one'], 3)})"


