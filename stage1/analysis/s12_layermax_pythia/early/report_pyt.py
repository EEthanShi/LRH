"""PYT-AXIS markdown report of implementation E (S0b sub-role pyt-code-E). GATED (plan F1(a)).

Copied from analysis/s12_layermax_openllama/early/report_ol.py (sha256 67580f2e...) and rewritten for the Pythia axis
(every function is new except the number formatting helpers f(), e(), jload(), which are kept). Layout kept: validation
table, decision rules, trends, diagnostics, files.

Every number is read from <RES>/summary.json (aggregate_pyt.py; its "v" block = verdicts_pyt.json), from E's validation
JSONs in <RES>/validation/, and, if present, from results/S1_2_layermax_pythia/forecast/E/verdicts_forecast.json
(sections F and K of VERDICTS_SPEC_PYT.md, written by forecast_pyt.py; the category is read there, never recomputed
here). Labels (plan section 5.4, 11 Reporting): only H1 and, behind its gate, H2 to H4 of the primary instance
(prh_clip+l2, s_cal) are confirmatory; every other number is descriptive and printed with that word. A reading written
after the numbers were seen may be added as early/interpretation.txt (labelled post hoc, plan F8).

Run (step S8, after aggregate_pyt.py, forecast_pyt.py --impl E and the validations; CPU, 1 thread):
  cd ~/hrh_v2_stage1_20261008 && analysis/s12_layermax_pythia/launch_pyt.sh pyt_E_report 1 -- \\
      venv/bin/python analysis/s12_layermax_pythia/early/report_pyt.py

Output: <RES>/REPORT.md
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import lm_core as LC  # noqa: E402  (constants and functions only; reads no data at import)

SZ = LC.SIZES  # PYT-AXIS
MET = {"mknn": "mKNN(10)", "cka_biased": "CKA biased", "cka_debiased": "CKA debiased"}


def f(x, n=3):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    try:
        return f"{x:.{n}f}"
    except Exception:
        return str(x)


def e(x):
    return "n/a" if x is None else f"{x:.1e}"


def jload(p):
    return json.load(open(p)) if os.path.exists(p) else None


def ok(b):  # PYT-AXIS
    return "n/a" if b is None else ("**PASS**" if b else "**FAIL**")


def main():
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    LC.gate("early/report_pyt.py")   # PYT-AXIS: plan F1(a), first action
    S = json.load(open(os.path.join(LC.RES, "summary.json")))
    v = S["v"]
    VD = os.path.join(LC.RES, "validation")
    V12 = jload(os.path.join(VD, "VP1_VP2_knn_tables.json"))
    V3 = jload(os.path.join(VD, "VP3.json"))
    V4 = jload(os.path.join(VD, "VP4_known_pairs.json"))
    V5 = jload(os.path.join(VD, "VP5_E_vs_I.json"))
    V7 = jload(os.path.join(VD, "VP7_prop5.json"))
    V8 = jload(os.path.join(VD, "VP8_generalisation.json"))
    V9 = jload(os.path.join(VD, "VP9_known_answers.json"))
    FK = jload(os.path.join(LC.PYT_FORECAST, "E", "verdicts_forecast.json"))
    fk = FK["v"] if FK else {}
    pres = [p for p in LC.PRES if v.get("G|l2_run") or p == LC.PRIMARY_PRE]
    L = []
    w = L.append
    w("# S1.2 Pythia axis: layer-max calibration, implementation E (Pythia 70M to 6.9B × 17 ViTs, WIT-1024)")
    w("")
    w("Plan: `analysis/s12_layermax_pythia/ANALYSIS_PLAN_PYTHIA.md` (Part A v1.0, sha256 6de89603…). Verdict contract: "
      "`VERDICTS_SPEC_PYT.md`. Code: `analysis/s12_layermax_pythia/early/` (changes in `early/CHANGES.md`). Generated by "
      "`early/report_pyt.py` from `" + os.path.relpath(os.path.join(LC.RES, "summary.json"), LC.PROJ) + "`.")
    w("")
    w("**Labels.** Confirmatory: H1 (gatekeeper) and, only if the gate is open, H2 to H4 under Holm, for the primary "
      "instance prh_clip+l2, s_cal (plan §5.4). Every other number is **descriptive**: uncensored and l2 versions, "
      "fixed depths, subsets, robustness, diagnostics, the cross-family table and the 18-LM panel (not ARH's panel). "
      "Exact p are over the 5040 relabellings of the sizes, conditional on the vision models and captions; bootstrap p "
      "resample ViTs only.")
    if LC.TEST:
        w("")
        w(f"**Mode: S0b test (stand-in data, not a result).** Part B read: `{LC.PARTB_JSON}`.")
    if not v.get("G|l2_run"):
        w("")
        w("**l2 not run** (plan §11 budget rule or S7 primary-only aggregate): every l2 key is null.")
    interp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "interpretation.txt")
    if os.path.exists(interp):   # plan F8: text written after the numbers were seen, labelled post hoc
        w("")
        w("## 0. Reading (post hoc: written after the numbers were seen)")
        w("")
        w(open(interp).read().strip())
    # ------------------------------------------------------------------ 1 validation
    w("")
    w("## 1. Validation (plan §11), E side")
    w("")
    w("| check | rule | result |")
    w("|---|---|---|")
    if V12:
        s1 = V12["summary"]
        w(f"| V-P1 clip thresholds | Pythia bitwise = `clip_thresholds_partB_pyt.json`; ViTs = S1.2 cache | "
          f"{ok(s1['VP1_pass'])} |")
        w(f"| V-P2 kNN tables | = hrhv2 knn_table every layer, both pre; ViT 0 boundary ties; ViT caches = frozen | "
          f"{s1['n_set_identical']}/{s1['n_tables']} set-identical; ViT boundary-tie layers "
          f"{len(s1['boundary_tie_layers']['B'])}; frozen {s1['frozen_cache_identical']}/{s1['frozen_cache_compared']}; "
          f"{ok(s1['VP2_pass'])} |")
    if V3:
        sm = V3["summary"]
        w(f"| V-P3 hrhv2 identity | 12 layer pairs × {{id, π0, π1, π499}} × 2 pre; CKA ≤ 1e-6, mKNN exact | "
          f"{sm['V2_n_cases']} cases, CKA max |Δ| {e(sm['V2_max_absdiff_cka'])}; {ok(sm['VP3_pass'])} |")
    if V4:
        w("| V-P4 known pairs | 4 reruns vs frozen E pair files; mKNN counts and p identical, CKA ≤ 1e-12 rel. | "
          + "; ".join(f"{p}: {r['n_pairs']} pairs, max rel {e(max(r['max_rel'].values()))}" for p, r in V4["per_pre"].items())
          + f"; {ok(V4['pass'])} |")
    if V5:
        r5 = V5.get("verdicts") or {}
        w(f"| V-P5 E vs I | pairs exact/1e-12; verdict keys EI and FK: 0 mismatches (counts and names only) | pairs "
          f"{ok((V5.get('pairs') or {}).get('pass'))}; EI {r5.get('EI', {}).get('n_mismatch', 'n/a')} mismatches; FK "
          f"{r5.get('FK', {}).get('n_mismatch', 'n/a')}; {ok(V5['pass'])} |")
    if V7:
        for p, R in V7["new_pairs_119"]["per_pre"].items():
            w(f"| V-P7 Prop. 5 ({p}) | biased median rel ≤ 3%, \\|z\\| > 4 ≤ 1% | biased median rel "
              f"{f(100 * R['cka_biased']['median_rel_err'], 2)}%; {ok(R['pass'])} |")
        w(f"| V-P7 debiased (b), (c); (d) descriptive | ≤ 1e-10; ≤ 1e-12 | (b) {e(V7['debiased_b_closed_form']['max_rel_to_largest'])}; "
          f"(c) {e(V7['debiased_c_plant']['max_abs_mean'])}; {ok(V7['debiased_b_closed_form']['pass'] and V7['debiased_c_plant']['pass'])} |")
    if V8:
        w(f"| V-P8 generalisation | legacy n = 3 reproduces OpenLLaMA A-C keys; n = 5 BLOOMZ trends and p | {ok(V8['pass'])} |")
    if V9:
        w(f"| V-P9 known answers (E) | pattern table, IUT, TOST, gate/Holm, P-P2b, category rows | {ok(V9['pass'])} |")
    w(f"| G | records read; V-P1 on the thresholds used | {v.get('G|n_pairs_read')} Pythia, {v.get('G|n_known_records')} "
      f"known; clip equal Part B {f(v.get('G|clip_equal_partB'))} |")
    pc = v.get("x|precat_checks_E_side", {})
    w("| Checks before any category (plan §7), E side | V-P1..V-P4, V-P7, P-P1, keep identity, sign rules, D3 | "
      + ", ".join(f"{k} {f(val_)}" for k, val_ in pc.items()) + " |")
    # ------------------------------------------------------------------ 2 confirmatory family
    for pre in pres:
        for x in ("s_cal", "unc"):
            h = f"H|{pre}|{x}"
            lab = "confirmatory" if (pre, x) == (LC.PRIMARY_PRE, "s_cal") else "descriptive"
            w("")
            w(f"## 2. Family of plan §5.4, `{pre}`, `{x}` ({lab})")
            w("")
            w("| test | statistic | p | decision |")
            w("|---|---|---|---|")
            w(f"| H1 (member {f(v[h + '|H1|member'])}, s = {v[h + '|H1|s']}) | D₁ = {f(v[h + '|H1|D'])} on {v[h + '|H1|nV']} ViTs "
              f"(R {f(v[h + '|H1|R'])} → C {f(v[h + '|H1|C'])}); CI [{f(v[h + '|H1|ci_lo'])}, {f(v[h + '|H1|ci_hi'])}] | "
              f"p_perm {e(v[h + '|H1|p_perm'])}, p_mag {e(v[h + '|H1|p_mag'])}, p {e(v[h + '|H1|p'])} | confirmed "
              f"{f(v[h + '|H1|confirmed'])}; gate {v[h + '|gate']}; knife edge {f(v[h + '|H1|kedge'])} |")
            w(f"| H2 ({v[h + '|H2|branch']}, s_late = {v[h + '|H2|s_late']}) | D₂ = {f(v[h + '|H2|D'])} | p {e(v[h + '|H2|p'])}"
              f" | tested {f(v[h + '|H2|tested'])}, Holm p {e(v[h + '|H2|p_holm'])}, confirmed {f(v[h + '|H2|confirmed'])} |")
            for hy in ("H3", "H4"):
                w(f"| {hy} (TOST, margin 0.10) | Δ = {f(v[h + '|' + hy + '|D'])}; degenerate {f(v[h + '|' + hy + '|degenerate'])} | "
                  f"p {e(v[h + '|' + hy + '|p'])} | tested {f(v[h + '|' + hy + '|tested'])}, Holm p "
                  f"{e(v[h + '|' + hy + '|p_holm'])}, confirmed {f(v[h + '|' + hy + '|confirmed'])} |")
            k = f"K|{pre}|{x}"
            if fk:
                w("")
                w(f"Category (plan §7, read from forecast/E section K): **{fk.get(k + '|category')}** "
                  f"(premise {fk.get(k + '|premise')}; F reason {fk.get(k + '|F_reason')}); modifiers M1 "
                  f"{fk.get(k + '|M1')} ({fk.get(k + '|M1_sizes')}), M2 {fk.get(k + '|M2')}, M3 {fk.get(k + '|M3')}, M4 "
                  f"{fk.get(k + '|M4')}, M5 {fk.get(k + '|M5_A')}/{fk.get(k + '|M5_B')}; readings H2 "
                  f"{fk.get(k + '|H2_reading')}, H3 {fk.get(k + '|H3_reading')}, H4 {fk.get(k + '|H4_reading')}.")
            own = v.get(f"x|E_own|category|{pre}|{x}")
            if own:
                w("")
                w(f"E's own reading of the §7 table (x| extra, cross-check only): {own['category']} "
                  f"(F reason {own['F_reason']}, premise {own['premise']}); E's own P-P2b: "
                  f"{v.get(f'x|E_own|PP2b|{pre}|{x}')}.")
            r = f"R|{pre}|{x}"
            w("")
            w(f"Robustness (descriptive, §5.5): fragile {f(v[r + '|fragile'])} ({v[r + '|fragile_sizes']}); five sizes D₁ "
              f"{f(v[r + '|five|D1'])} (carried by 70M/160M {f(v[r + '|five|carried'])}); grid5 D₁ {f(v[r + '|grid5|D1'])}, "
              f"mKNN {f(v[r + '|grid5|dtr_mknn'])}, debiased {f(v[r + '|grid5|dtr_dcka'])}; ρ:=0 D₁ {f(v[r + '|rho0|D1'])}; "
              "leave-one-ViT-family-out D₁ " + ", ".join(f"{fam} {f(v[r + '|lofo|' + fam + '|D1'])}"
                                                        for fam in ("in21k", "MAE", "DINOv2", "CLIP")) + ".")
    # ------------------------------------------------------------------ 3 premise rules
    for pre in pres:
        w("")
        w(f"## 3. Premise rules (plan §9), `{pre}`")
        w("")
        w("| rule | s_cal | unc (secondary) |")
        w("|---|---|---|")
        w(f"| P-P1 (mKNN ζ; reversals = implementation error) | nrev {v[f'PP1|{pre}|s_cal|nrev']} of "
          f"{v[f'PP1|{pre}|s_cal|nq']}, ties {v[f'PP1|{pre}|s_cal|ntie']} | nrev {v[f'PP1|{pre}|unc|nrev']} of "
          f"{v[f'PP1|{pre}|unc|nq']} |")
        w(f"| P-P2a(i) models in band (≥ 6 of 7) | {v[f'PP2ai|{pre}|s_cal|n_models_in_band']} "
          f"(failing: {v[f'PP2ai|{pre}|s_cal|failing'] or 'none'}); flat band {v[f'PP2ai|{pre}|s_cal|flat|n_models_in_band']} | "
          f"{v[f'PP2ai|{pre}|unc|n_models_in_band']} |")
        w(f"| P-P2a(ii) consistency (⌈0.9n⌉) | {v[f'PP2aii|{pre}|s_cal|x']}/{v[f'PP2aii|{pre}|s_cal|n']} "
          f"{v[f'PP2aii|{pre}|s_cal|verdict']} | {v[f'PP2aii|{pre}|unc|x']}/{v[f'PP2aii|{pre}|unc|n']} "
          f"{v[f'PP2aii|{pre}|unc|verdict']} |")
        w(f"| P-P2a | {v[f'PP2a|{pre}|s_cal|verdict']} | {v[f'PP2a|{pre}|unc|verdict']} |")
        if fk:
            w(f"| P-P2b (forecast_pyt.py, E) | {fk.get(f'PP2b|{pre}|s_cal|x_correct')}/{fk.get(f'PP2b|{pre}|s_cal|n_decided')}"
              f" {fk.get(f'PP2b|{pre}|s_cal|verdict')} | {fk.get(f'PP2b|{pre}|unc|x_correct')}/"
              f"{fk.get(f'PP2b|{pre}|unc|n_decided')} {fk.get(f'PP2b|{pre}|unc|verdict')} |")
        w(f"| P-P5a (⌈2n/3⌉) | {v[f'PP5a|{pre}|s_cal|x']}/{v[f'PP5a|{pre}|s_cal|n']} {v[f'PP5a|{pre}|s_cal|verdict']} | "
          f"{v[f'PP5a|{pre}|unc|x']}/{v[f'PP5a|{pre}|unc|n']} {v[f'PP5a|{pre}|unc|verdict']} |")
        w(f"| P-P3 fixed depth r = 0.5 / 1.0 (descriptive) | {v[f'PP3|{pre}|0.5|s_cal|desc']} / {v[f'PP3|{pre}|1.0|s_cal|desc']}"
          f" | {v[f'PP3|{pre}|0.5|unc|desc']} / {v[f'PP3|{pre}|1.0|unc|desc']} |")
        nk = sum(val_ for k_, val_ in v.items() if k_.startswith(f"keepid|{pre}|") and val_)
        ns = sum(val_ for k_, val_ in v.items() if k_.startswith(f"signrule|{pre}|") and val_)
        nsv = sum(val_ for k_, val_ in v.items() if k_.startswith(f"signvit|{pre}|") and ("|nviol_" in k_) and val_)
        nex = sum(val_ for k_, val_ in v.items() if k_.startswith(f"signvit|{pre}|") and k_.endswith("|nexcl_tie") and val_)
        w("")
        w(f"Implementation checks (errors if nonzero): keep identity {nk}, per-comparison sign rule {ns}, per-ViT sign rule "
          f"{nsv} ({nex} ViT cases excluded for a censoring tie, spec §5 [plan-gap]), D3 {v[f'D3|{pre}|nviol']} "
          f"({v[f'D3|{pre}|nexcl_tie']} excluded). Plug-in Tr(T − B̄) {f(v[f'plugin|{pre}|tr'])}, difference to Tr(unc) on "
          f"{v[f'plugin|{pre}|nv']} ViTs {f(v[f'plugin|{pre}|diff'])} (within 0.10: {f(v[f'plugin|{pre}|within'])}). "
          f"OP-style reading (descriptive): CKA {v[f'readO|{pre}|cka_biased']}, debiased {v[f'readO|{pre}|cka_debiased']}.")
    # ------------------------------------------------------------------ 4 trends (descriptive tables)
    for pre in pres:
        w("")
        w(f"## 4. Trends over the 7 sizes, layer-max `full`, `{pre}` (Tr_P, exact one-sided p; descriptive except §2)")
        w("")
        w("| metric | raw | s_cal | unc | ΔTr s_cal (p↓) | ΔTr unc (p↓) | f₋/f₊ of 357 (s_cal) |")
        w("|---|---|---|---|---|---|---|")
        for m in ("mknn", "cka_biased", "cka_debiased"):
            t = lambda X: v.get(f"tr|{pre}|{m}|full|{X}")  # noqa: E731
            d = lambda X: v.get(f"dtr|{pre}|{m}|full|{X}")  # noqa: E731
            w(f"| {MET[m]} | {f(t('raw'))} | {f(t('s_cal'))} | {f(t('unc'))} | {f(d('s_cal'))} "
              f"({e(v.get(f'dtr_ple|{pre}|{m}|full|s_cal'))}) | {f(d('unc'))} ({e(v.get(f'dtr_ple|{pre}|{m}|full|unc'))}) | "
              f"{v.get(f'fcnt|{pre}|{m}|full|s_cal|fminus')}/{v.get(f'fcnt|{pre}|{m}|full|s_cal|fplus')} |")
        w("")
        w("Cross-family table (descriptive; Tr over each family's own sizes, layer-max, biased CKA): " + "; ".join(
            f"{fam} {f(v.get(f'famtr|{pre}|cka_biased|raw|{fam}'))} → {f(v.get(f'famtr|{pre}|cka_biased|s_cal|{fam}'))}"
            for fam in ("BLOOMZ", "LLaMA", "OpenLLaMA", "Pythia")) + ". 18-LM panel r (raw → s_cal; not ARH's panel): "
            f"{f(v.get(f'panel18|{pre}|cka_biased|raw|r'))} → {f(v.get(f'panel18|{pre}|cka_biased|s_cal|r'))}.")
        w("")
        w(f"Diagnostics (descriptive): D5 g = {f(v.get(f'D5|{pre}|g'), 4)}, h = {f(v.get(f'D5|{pre}|h'), 4)} per doubling; "
          f"D4 Spearman with log params: PR* {f(v.get(f'D4|{pre}|PRstar|logparams'))}, B̄ {f(v.get(f'D4|{pre}|Bbar|logparams'))}, "
          f"c_α {f(v.get(f'D4|{pre}|calpha|logparams'))}, T {f(v.get(f'D4|{pre}|T|logparams'))}; D6 Spearman(c − base, "
          f"L_stored): mKNN {f(v.get(f'D6|{pre}|mknn|spearman_L'))}, debiased {f(v.get(f'D6|{pre}|cka_debiased|spearman_L'))}.")
    # ------------------------------------------------------------------ 5 files
    w("")
    w("## 5. Files")
    w("")
    for k_, h_ in S.get("inputs", {}).items():
        w(f"- `{k_}`: `{h_}`")
    w("")
    with open(os.path.join(LC.RES, "REPORT.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"written {LC.RES}/REPORT.md", flush=True)


if __name__ == "__main__":
    main()
