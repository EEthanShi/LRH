def f(x, nd=3):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int,)) and not isinstance(x, bool):
        return str(x)
    if abs(x) != 0 and (abs(x) < 10 ** (-nd) or abs(x) >= 1e4):
        return f"{x:.2e}"
    return f"{x:.{nd}f}"


def ci(t, nd=3):
    """(est, lo, hi) -> 'est [lo, hi]'"""
    return f"{f(t[0], nd)} [{f(t[1], nd)}, {f(t[2], nd)}]"


