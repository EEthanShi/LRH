def f(x, n=3):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    try:
        return f"{x:.{n}f}"
    except Exception:
        return str(x)


def e(x):
    return "n/a" if x is None else f"{x:.1e}"


def trl(P, key, n=2):
    t = P["trends_L"][key]
    if t["Tr"] is None:
        return "n/a (all ViTs constant)"
    ci = t.get("ci")
    s = f"{f(t['Tr'], n)}"
    if ci:
        s += f" [{f(ci[0], n)}, {f(ci[1], n)}]"
    s += f" (p₁={f(t['p_one'], 3)})"
    if t["n_vit_constant"]:
        s += f" ({t['n_vit_constant']} const.)"
    return s


def dtr(P, key, n=2):
    d = P["delta_L"][key]
    if d.get("diff") is None:
        return "n/a"
    return f"{f(d['diff'], n)} (p↓={f(d['p_lower'], 3)}, p↑={f(d['p_upper'], 3)})"


def triple(dct, n=4):
    return " / ".join(f(dct[lm], n) for lm in LL)


